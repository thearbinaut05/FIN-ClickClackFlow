import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = p => fs.readFileSync(new URL('../' + p, import.meta.url), 'utf8');
const server = read('cashout-server.js');
const cloud = read('src/services/LovableCloudService.ts');
const ui = read('src/components/game/AutonomousRevenueDisplay.tsx');
test('legacy browser balance cannot invent funds or completed transactions', () => {
  assert.doesNotMatch(cloud, /localStorage|150\.75|pi_mock_|txn_local_|status: ['"]succeeded/);
  assert.match(cloud, /getRevenueBalance[\s\S]*?throw new Error\(UNVERIFIED\)/);
  assert.match(cloud, /healthCheck[\s\S]*?return false/);
});
test('legacy payment creation fails closed', () => {
  assert.match(cloud, /createPaymentIntent[\s\S]*?throw new Error\(UNVERIFIED\)/);
  assert.match(cloud, /processCashout[\s\S]*?success: false/);
});
test('email receipt never reports payout success or calls a provider', async () => {
  const source = server.slice(server.indexOf('async function performEmailPayout('), server.indexOf('// Onboarding link endpoint'));
  const context = vm.createContext({});
  vm.runInContext(source + ';globalThis.run = performEmailPayout;', context);
  for (const amount of [1, 100, NaN, -100]) {
    const result = await context.run('owner@example.com', amount);
    assert.equal(result.success, false);
    assert.equal(result.code, 'EMAIL_PAYOUT_UNSUPPORTED');
    assert.equal(result.paymentIntentId, undefined);
  }
});
test('money-moving route guard executes before cashout handlers and does not call next', () => {
  const start = server.indexOf("app.use(['/cashout'");
  const end = server.indexOf('\n});', start) + 4;
  assert.ok(start >= 0 && start < server.indexOf("app.post('/cashout'"));
  let paths, handler;
  vm.runInNewContext(server.slice(start, end), { app: { use: (p,h) => { paths=p; handler=h; } } });
  for (const route of ['/cashout','/sweep-usd','/usd-sweep','/transfer-accounts']) assert.ok(paths.includes(route));
  let code, body;
  const res = { status: n => { code=n;return res; }, json: b => { body=b;return res; } };
  handler({method:'POST'},res,()=>assert.fail('unsafe route reached'));
  assert.equal(code,503); assert.equal(body.success,false);
  assert.equal(body.code,'UNVERIFIED_PAYOUT_PATH_DISABLED');
});
test('unavailable balance is not displayed as available cash', () => {
  assert.doesNotMatch(ui, /demo_user_|Ready|Building|generated by direct revenue/);
  assert.match(ui, /setBalance\(null\)/);
  assert.match(ui, /balance === null \? 'Unavailable'/);
});
